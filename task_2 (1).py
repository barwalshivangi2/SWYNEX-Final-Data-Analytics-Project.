import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Dataset load karna
df = pd.read_csv("cleaned_dataset.csv")
print(df.describe())


plt.style.use('dark_background')
sns.set_theme(style="darkgrid", rc={
    "axes.facecolor": "#151521",
    "figure.facecolor": "#151521",
    "grid.color": "#2b2b40",
    "text.color": "white",
    "axes.labelcolor": "white",
    "xtick.color": "#b5b5c3",
    "ytick.color": "#b5b5c3"
})

fig = plt.figure(figsize=(16, 10))
fig.patch.set_facecolor('#151521')


plt.subplot(2, 2, 1)
sns.countplot(x='Survived', data=df, palette=['#ff4a4a', '#00e5ff'])
plt.title('Overall Survival Summary', fontsize=16, color='white', pad=15)
plt.xlabel('Survived (0 = No, 1 = Yes)', fontsize=12)
plt.ylabel('Count', fontsize=12)

# 2. Survival by Gender
plt.subplot(2, 2, 2)
sns.countplot(x='Survived', hue='Sex', data=df, palette=['#b23cff', '#2962ff'])
plt.title('Survival Breakdown by Gender', fontsize=16, color='white', pad=15)
plt.xlabel('Survived', fontsize=12)
plt.ylabel('Count', fontsize=12)

# 3. Age Distribution
plt.subplot(2, 2, 3)
sns.histplot(df['Age'], bins=20, kde=True, color='#b23cff', edgecolor='white', alpha=0.6)
plt.title('Age Distribution of Passengers', fontsize=16, color='white', pad=15)
plt.xlabel('Age (Years)', fontsize=12)
plt.ylabel('Passenger Count', fontsize=12)

# 4. Fare Distribution
plt.subplot(2, 2, 4)
sns.boxplot(x='Pclass', y='Fare', data=df, palette=['#ffc400', '#00e5ff', '#ff3d00'])
plt.title('Fare Distribution by Passenger Class', fontsize=16, color='white', pad=15)
plt.xlabel('Passenger Class', fontsize=12)
plt.ylabel('Fare', fontsize=12)

plt.tight_layout(pad=3.0)
plt.savefig('premium_eda_charts.png', facecolor=fig.get_facecolor(), edgecolor='none')
plt.show()

# 5 Insights Output
print("\n--- 5 Useful Insights ---")
print("1. Survival Rate: Overall survival rate was low; majority of the passengers did not survive.")
print("2. Gender Pattern: Females had a significantly higher survival rate compared to males.")
print("3. Age Trend: Most passengers were young adults (20-30 years).")
print("4. Class Impact: 1st class passengers paid much higher fares and had better survival chances.")
print("5. Anomalies/Outliers: Extreme outliers exist in the 'Fare' column, indicating exceptionally high prices paid by a few.")